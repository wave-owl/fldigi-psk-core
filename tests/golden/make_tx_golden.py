#!/usr/bin/env python3
"""Regenerate the TX golden data in tests/golden/tx from a wave-owl checkout.

Usage (with the wave-owl virtualenv active):

    python tests/golden/make_tx_golden.py /path/to/wave-owl [out_dir]

For each fldigi 4.2.13 reference vector ``src/modes/psk/vectors/<name>.{wav,json}`` of
wave-owl (headless fldigi TX, 8000 Hz, carrier 1500 Hz, txlevel -12 dB, 16-bit PCM):

* ``<name>.s16`` -- the WAV samples as little-endian int16 raw data (unchanged).
* ``<name>.bits`` -- the varicode bit stream of the vector text, one line of ``0``/``1``
  after ``#`` comment lines, generated with wave-owl
  ``src.modes.psk.varicode.encode_bits(text)`` (each codeword followed by the ``00`` gap,
  fldigi ``psk::tx_char``, psk.cxx:2470-2493).
"""

import hashlib
import json
import os
import sys

import numpy as np
import soundfile as sf

VECTORS = ("psk31_cq", "psk63_cq", "psk125_pangram")


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    wave_owl = os.path.abspath(sys.argv[1])
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.abspath(sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "tx"))
    sys.path.insert(0, wave_owl)
    from src.modes.psk.varicode import encode_bits

    os.makedirs(out, exist_ok=True)
    vec_dir = os.path.join(wave_owl, "src", "modes", "psk", "vectors")
    for name in VECTORS:
        with open(os.path.join(vec_dir, name + ".json")) as f:
            meta = json.load(f)
        wav = os.path.join(vec_dir, name + ".wav")
        with open(wav, "rb") as f:
            if hashlib.sha256(f.read()).hexdigest() != meta["sha256"]:
                sys.exit("sha256 mismatch for %s" % wav)
        pcm, rate = sf.read(wav, dtype="int16")
        assert rate == 8000 and pcm.ndim == 1, name
        pcm.astype("<i2").tofile(os.path.join(out, name + ".s16"))
        text = meta["generator"]["environment"]["FLDIGI_BENCH_TX_TEXT"]
        bits = encode_bits(text)
        with open(os.path.join(out, name + ".bits"), "w") as f:
            f.write("# %s %s carrier_hz=%d txlevel_db=%.1f samples=%d\n"
                    % (name, meta["submode"], meta["fldigi_mode"]["carrier_hz"],
                       meta["fldigi_mode"]["txlevel_db"], len(pcm)))
            f.write("# text: %s\n" % text)
            f.write("# generated by tests/golden/make_tx_golden.py with wave-owl "
                    "src.modes.psk.varicode.encode_bits(text)\n")
            f.write("".join(str(b) for b in bits) + "\n")
        print("%s: %d samples, %d bits" % (name, len(pcm), len(bits)))


if __name__ == "__main__":
    main()
